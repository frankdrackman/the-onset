const key = (n) => n.split(',')[0].toLowerCase().replace(/[^a-z]/g, '');
const shortKey = (n) => {
  const p = n.split(',')[0].match(/[A-Za-z']+/g) || [];
  return p.length >= 2 ? (p[0] + p[p.length - 1]).toLowerCase() : '';
};
